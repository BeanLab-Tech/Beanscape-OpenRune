-- Beanscape Grand Exchange on Postgres (ported from the rev 233 SQLite migrations V7 + V8).
-- Lives in the `beanlab` schema so it never collides with OpenRune Central's own tables.

CREATE TABLE IF NOT EXISTS beanlab.ge_offers (
    id BIGINT PRIMARY KEY,
    account_id INTEGER NOT NULL,
    slot INTEGER NOT NULL,
    type TEXT NOT NULL CHECK (type IN ('BUY', 'SELL')),
    item_id INTEGER NOT NULL,
    quantity INTEGER NOT NULL,
    remaining INTEGER NOT NULL,
    price_per BIGINT NOT NULL,
    gold_escrow BIGINT NOT NULL DEFAULT 0,
    gold_spent BIGINT NOT NULL DEFAULT 0,
    proceeds_gold BIGINT NOT NULL DEFAULT 0,
    items_filled INTEGER NOT NULL DEFAULT 0,
    tax_paid BIGINT NOT NULL DEFAULT 0,
    state TEXT NOT NULL CHECK (state IN ('ACTIVE', 'COMPLETED', 'CANCELLED', 'COLLECTED')),
    -- Writes run on a multi-threaded pool and may arrive out of order; the upsert only accepts a
    -- newer revision.
    revision BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_ge_offers_item_state ON beanlab.ge_offers (item_id, state);
CREATE INDEX IF NOT EXISTS idx_ge_offers_account_state ON beanlab.ge_offers (account_id, state);

CREATE TABLE IF NOT EXISTS beanlab.ge_history (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    item_id INTEGER NOT NULL,
    quantity INTEGER NOT NULL,
    price_per BIGINT NOT NULL,
    gross BIGINT NOT NULL,
    tax BIGINT NOT NULL,
    buyer_account_id INTEGER NOT NULL,
    seller_account_id INTEGER NOT NULL,
    -- A buy/sell pair matches at most once, so the pair identifies a trade and makes retried
    -- inserts no-ops.
    buy_offer_id BIGINT,
    sell_offer_id BIGINT,
    traded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_ge_history_item_time ON beanlab.ge_history (item_id, traded_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS idx_ge_history_offer_pair
    ON beanlab.ge_history (buy_offer_id, sell_offer_id);
