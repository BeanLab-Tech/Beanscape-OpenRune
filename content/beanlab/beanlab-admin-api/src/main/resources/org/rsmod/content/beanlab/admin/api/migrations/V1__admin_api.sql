-- Admin console API (ported from rev 233 V12/V15). Lives in the `beanlab` schema; accounts are
-- OpenRune Central's `public.accounts`.

CREATE TABLE IF NOT EXISTS beanlab.admin_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id INTEGER NOT NULL REFERENCES public.accounts (id) ON DELETE CASCADE,
    -- SHA-256 of the raw token; the raw token is shown once in game and never stored.
    token_hash TEXT NOT NULL UNIQUE,
    label TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_used_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_admin_tokens_account ON beanlab.admin_tokens (account_id);

CREATE TABLE IF NOT EXISTS beanlab.admin_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actor_account_id INTEGER NOT NULL,
    actor TEXT NOT NULL,
    action TEXT NOT NULL,
    target TEXT,
    detail TEXT,
    ok BOOLEAN NOT NULL
);

-- Central's `accounts.rights` only has NONE / MOD / ADMINISTRATOR. Beanscape's owner rank sits on
-- top of ADMINISTRATOR: an account listed here is an owner.
CREATE TABLE IF NOT EXISTS beanlab.owners (
    account_id INTEGER PRIMARY KEY REFERENCES public.accounts (id) ON DELETE CASCADE
);
